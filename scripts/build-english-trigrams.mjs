#!/usr/bin/env node
/**
 * SPDX-License-Identifier: GPL-3.0-or-later
 *
 * Regenerate `src/node/tools/lib/english-trigrams.mjs` from this repository's own English prose.
 *
 * A committed data blob nobody can reproduce is a liability, not an asset -- the first question
 * anyone asks of a frequency table is where it came from, and "it was in the commit" is not an
 * answer. This is that answer. Run it after a documentation pass if you want the model refreshed;
 * nothing requires you to, because the table changes very little and a stale one is not a defect.
 *
 *     node scripts/build-english-trigrams.mjs
 *
 * @author DoubleGate
 * @license GPL-3.0-or-later
 */

import { readFileSync, writeFileSync, readdirSync } from "node:fs";
import { dirname, join, extname } from "node:path";
import { fileURLToPath } from "node:url";

const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const OUTPUT = join(ROOT, "src/node/tools/lib/english-trigrams.mjs");

/** Directories never worth walking, whatever they contain. */
const SKIP = new Set(["node_modules", ".git", "ref-proj", "coverage", "build", "vendor"]);

/**
 * Files excluded by name.
 *
 * `index.mjs` under `src/node` is GENERATED by grunt and gitignored, so including it would make
 * the table depend on whether the build had been run -- two checkouts would produce different
 * committed data from the same source. A generated table has to be reproducible or it is a blob.
 *
 * `english-trigrams.mjs` is this script's OWN OUTPUT, and excluding it closes a feedback loop that
 * is not obvious: base64 contains `//`, the comment scanner below matches `//.*` to end of line,
 * so the table's own encoded bytes were being read back in as English prose. Two consecutive runs
 * produced corpora differing by fifty letters, which is how it was found.
 */
const SKIP_FILES = new Set(["index.mjs", "english-trigrams.mjs"]);

/**
 * Every file under `start` with one of the given extensions.
 *
 * A directory walk rather than a shell `find`: no shell means no quoting question to get wrong,
 * and this script is the sort that gets copied into another repository with a path substituted.
 *
 * @param {string} start - Directory to walk, relative to the repository root.
 * @param {string[]} extensions - Extensions to keep, with the dot.
 * @returns {string[]} Absolute paths.
 */
function walk(start, extensions) {
    const out = [];
    const stack = [join(ROOT, start)];
    while (stack.length) {
        const directory = stack.pop();
        let entries;
        try {
            entries = readdirSync(directory, { withFileTypes: true });
        } catch {
            continue;
        }
        for (const entry of entries) {
            if (SKIP.has(entry.name)) continue;
            const path = join(directory, entry.name);
            if (entry.isDirectory()) stack.push(path);
            else if (extensions.includes(extname(entry.name)) && !SKIP_FILES.has(entry.name)) out.push(path);
        }
    }
    return out;
}

/** @returns {string} Every letter of the corpus, uppercased, with everything else removed. */
function gatherCorpus() {
    let text = "";
    for (const file of [...walk("docs", [".md"]), join(ROOT, "README.md"), join(ROOT, "CHANGELOG.md")]) {
        try {
            text += readFileSync(file, "utf8") + "\n";
        } catch {
            // A path that vanished between listing and reading is not worth failing over.
        }
    }
    // Comment text from our own source. In this project comments are ordinary English at length,
    // which nearly doubles the corpus; the code around them is excluded, since identifiers and
    // hex constants would poison a letter-frequency model.
    for (const file of [...walk("src/node", [".mjs"]), ...walk("tests/mcp", [".mjs"])]) {
        try {
            const source = readFileSync(file, "utf8");
            for (const match of source.matchAll(/\/\*[\s\S]*?\*\/|\/\/.*/g)) text += match[0] + "\n";
        } catch {
            // As above.
        }
    }
    return text
        .replace(/```[\s\S]*?```/g, " ")
        .replace(/`[^`]*`/g, " ")
        .replace(/https?:\/\/\S+/g, " ")
        .toUpperCase()
        .replace(/[^A-Z]/g, "");
}

const letters = gatherCorpus();
const counts = new Float64Array(26 * 26 * 26);
for (let i = 0; i + 2 < letters.length; i++) {
    counts[(letters.charCodeAt(i) - 65) * 676 +
        (letters.charCodeAt(i + 1) - 65) * 26 +
        (letters.charCodeAt(i + 2) - 65)]++;
}

const distinct = counts.reduce((n, c) => n + (c > 0 ? 1 : 0), 0);
const max = counts.reduce((m, c) => Math.max(m, c), 0);
const packed = new Uint16Array(counts.length);
let lost = 0;
for (let i = 0; i < counts.length; i++) {
    packed[i] = Math.round(counts[i] / max * 65535);
    if (counts[i] > 0 && packed[i] === 0) lost++;
}

const b64 = Buffer.from(packed.buffer).toString("base64");
const existing = readFileSync(OUTPUT, "utf8");
const updated = existing
    .replace(/export const TRIGRAM_CORPUS_LETTERS = \d+;/, `export const TRIGRAM_CORPUS_LETTERS = ${letters.length};`)
    .replace(/(export const TRIGRAM_TABLE_B64 =\n {4}")[^"]*(";)/, `$1${b64}$2`);
writeFileSync(OUTPUT, updated);

process.stdout.write(
    `letters ${letters.length}, distinct trigrams ${distinct} ` +
    `(${(100 * distinct / counts.length).toFixed(1)}% of space), ` +
    `${lost} lost to quantisation, ${(b64.length / 1024).toFixed(0)} KB written\n`);
